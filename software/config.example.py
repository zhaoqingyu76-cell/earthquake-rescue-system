# ================= 危险判定：以色纸为中心的 5cm 警戒框 =================
# 新逻辑：以检测到的每张纸(水源区/坑区)的色块边界为中心，向外扩 DANGER_RADIUS 像素，
# 形成一个"警戒框"。当小车(ArUco 定位的中心点)进入警戒框内 -> 停车并接 DeepSeek 研判。
# 警戒框 = 色纸 bbox 向外扩 DANGER_RADIUS_PX。
#
# 距离换算：PIXELS_PER_CM 表示"画面上 1 厘米对应多少像素"。需要现场标定：
#   - 俯拍离地面越近，像素密度越高(该值越大)；离得越远则越小。
#   - 标定方法：放一把尺在地面，看画面上多少像素 = 10cm，再 /10 即可。
#   - 若暂时不想精确标定，可手调 DANGER_RADIUS 像素值，让触发时机符合预期即可。
PIXELS_PER_CM = 12          # 现场标定：1cm = 几像素（俯拍视角而定）
DANGER_RADIUS_CM = 2        # 接近触发判定的距离（厘米）——"小车临近纸就停"
DANGER_RADIUS_PX = int(PIXELS_PER_CM * DANGER_RADIUS_CM)   # = 2cm 对应像素

