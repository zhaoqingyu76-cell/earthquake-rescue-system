# 遇到危险停车后，审查期间每 0.3s 重申一次 s，防止小车因异常继续动
HOLD_CHECK_INTERVAL = 0.3
# "从旁边绕"的绕行时序参数（秒）：[1]后先转向避让多久，再前进多久绕过
ROUND_TURN_MS = 0.5     # 原地转向时长（决定转多少度，现场调）
ROUND_FWD_MS = 0.8      # 前进绕过时长（现场调）

# ================= 坐标向量绕行（问题3：按坐标算转向角） =================
# 不再"固定转90°"，而是根据 ArUco 车头朝向角 + 目标区 bbox 的横向偏移，
# 算出"该向右转多少度、直行多远"刚好绕过当前区。
# 注意：图像角度→电机转向时长的换算系数需现场标定一次：
#   放一张已知角度的参照（如让车原地转，用秒表量 90° 需要多少 ms 再除以90）。
ROUND_ANGLE_TO_MS = 12.0     # 转向 1° = 多少毫秒（现场标定；默认 90°≈1.1s）
# 自动转向单次时长硬上限（毫秒）。ROUND_ANGLE_TO_MS 若未标定偏大，
# 会导致"建议转18°实际转过180°"（看起来掉头向后/转不停）。此上限强制单次转向不失控
ROUND_MAX_TURN_MS = 2500
ROUND_CM_TO_MS = 260.0       # 直线前进 1cm = 多少毫秒（现场标定；默认 10cm≈2.6s）
AVOID_MARGIN_CM = 6          # 绕行时在区宽之外再多让出的安全边距（厘米）
# ArUco 车头朝向，使用【平面直角坐标系】且落在 [-180°,180°]：
#   0°=车头朝画面正右，90°=朝正上，±180°=朝正左，-90°=朝正下（是小车的方向，不是画面方向）。
# YAW_SIGN：符号校正。若屏幕与图像 y 轴方向导致角度符号反了，改 +1/-1。
# YAW_HEAD_OFF：基准偏置。若码贴向让数值整体偏了 N°，设成 N 来对齐到直角坐标系。
#   （车实际朝画面正上方时希望读到 90°、朝正右读到 0°，据此增减 YAW_HEAD_OFF。）
YAW_SIGN = 1.0               # 朝向符号校正
YAW_HEAD_OFF = 0.0           # 朝向基准偏置(度)，默认 0；按"朝正上应=90°"现场增减
# 转向方向可调：若画面"建议右转"但箭头/实车往左，把它改 -1.0（与 YAW_SIGN 同理，现场标定）
