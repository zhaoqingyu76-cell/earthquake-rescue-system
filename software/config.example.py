# ================= DeepSeek =================
# DeepSeek Key 的填法（二选一）：
# 1) 环境变量：export DEEPSEEK_API_KEY="YOUR_DEEPSEEK_API_KEY"
# 2) 启动时输入：没设环境变量时，程序启动会问你输入 Key，直接回车就是不用。
# Key 只存在内存里，绝不写进代码/仓库。（或写进本地 .env，不提交）
DEEPSEEK_API_KEY = os.environ.get("DEEPSEEK_API_KEY", "")


def ask_deepseek_key():
    """启动时问一次 Key：已设环境变量就不问；直接回车 = 不用 DeepSeek，用本地降级研判。"""
    global DEEPSEEK_API_KEY
    if DEEPSEEK_API_KEY:
        return DEEPSEEK_API_KEY
    try:
        typed = input("请输入 DeepSeek Key（直接回车跳过，不用在线研判）: ").strip()
    except (EOFError, KeyboardInterrupt):
        typed = ""
    DEEPSEEK_API_KEY = typed
    return DEEPSEEK_API_KEY
